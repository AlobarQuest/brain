def derive_repo(git_repository: str | None) -> str | None:
    """Parse a Coolify `git_repository` to canonical 'Owner/Repo' (case preserved).

    Handles SSH (git@github.com:Owner/Repo.git), HTTPS
    (https://github.com/Owner/Repo.git), and the bare 'Owner/Repo' Coolify often
    stores. Returns None if it can't extract two path segments.

    >>> derive_repo("git@github.com:AlobarQuest/booking-system.git")
    'AlobarQuest/booking-system'
    >>> derive_repo("AlobarQuest/booking-system")
    'AlobarQuest/booking-system'
    """
    if not git_repository:
        return None
    s = git_repository.strip()
    if not s:
        return None
    scp = re.match(r"^[\w.+-]+@[\w.-]+:(.+)$", s)
    if scp:
        path = scp.group(1)
    else:
        url = re.match(r"^[a-zA-Z][\w+.-]*://(?:[^@/]+@)?[^/]+/(.+)$", s)
        path = url.group(1) if url else s  # bare 'owner/repo'
    path = path.strip("/")
    if path.endswith(".git"):
        path = path[: -len(".git")]
    parts = [p for p in path.split("/") if p]
    if len(parts) < 2:
        return None
    return f"{parts[0]}/{parts[1]}"


def _is_ip(host: str | None) -> bool:
    return bool(host) and bool(re.fullmatch(r"\d{1,3}(?:\.\d{1,3}){3}", host))


def _is_autogenerated(host: str | None) -> bool:
    """A Coolify auto-generated host (*.sslip.io or a bare IP) rather than a custom domain."""
    return bool(host) and (host.endswith(".sslip.io") or _is_ip(host))


def pick_fqdn(fqdn: str | None) -> str | None:
    """Choose the best URL from a Coolify `fqdn` (which may be comma-separated).

    Prefers a real custom domain over Coolify's auto-generated *.sslip.io / IP host,
    but falls back to the auto-generated one rather than dropping the env. Returns an
    https-normalized URL (scheme added if missing, trailing slash trimmed), or None.

    >>> pick_fqdn("https://x.sslip.io,https://preview.booking.devonwatkins.com")
    'https://preview.booking.devonwatkins.com'
    """
    if not fqdn:
        return None
    candidates = []
    for raw in fqdn.split(","):
        raw = raw.strip()
        if not raw:
            continue
        url = raw if "://" in raw else f"https://{raw}"
        url = url.rstrip("/")
        candidates.append((url, normalize_host(url)))
    if not candidates:
        return None
    for url, host in candidates:
        if host and not _is_autogenerated(host):
            return url
    return candidates[0][0]


def _env_name(branch: str | None, host: str | None) -> str:
    if branch == "preview" or (host and host.startswith("preview.")):
        return "preview"
    return "prod"


def build_environment(coolify_app: dict) -> dict:
    """Build one {name, branch, url, coolify_app_uuid} record from a Coolify app.

    Exact contract shape (keeps the migration's array CHECK and the resolver happy).
    branch/url are exactly what Coolify reports (may be null) — never guessed.
    """
    url = pick_fqdn(coolify_app.get("fqdn"))
    host = normalize_host(url)
    branch = coolify_app.get("git_branch") or None
    return {
        "name": _env_name(branch, host),
        "branch": branch,
        "url": url,
        "coolify_app_uuid": coolify_app.get("uuid"),
    }


def map_coolify_to_app(
    coolify_apps: list[dict], appbrain_apps: list[dict]
) -> tuple[dict, list[dict]]:
    """Map Coolify applications onto app-brain apps.

    Returns (computed, unmapped):
      computed: {slug: {"github_repo": str|None, "environments": [records...]}}
      unmapped: Coolify apps that matched no app-brain record (logged, not invented).

    Match by git_repository (case-folded) first, then FQDN host (against an app's
    deployment_url host or any existing environment url host).
    """
    by_repo: dict[str, str] = {}
    by_host: dict[str, str] = {}
    for a in appbrain_apps:
        if a.get("github_repo"):
            by_repo.setdefault(a["github_repo"].lower(), a["slug"])
        h = normalize_host(a.get("deployment_url"))
        if h:
            by_host.setdefault(h, a["slug"])
        for e in a.get("environments") or []:
            eh = normalize_host(e.get("url"))
            if eh:
                by_host.setdefault(eh, a["slug"])

    computed: dict[str, dict] = {}
    unmapped: list[dict] = []
    for c in coolify_apps:
        repo = derive_repo(c.get("git_repository"))
        # A repo is trustworthy as github_repo ONLY if it matched an app-brain app.
        # dockerimage apps report a placeholder git_repository ("coollabsio/coolify")
        # and map via fqdn — never let that placeholder become a github_repo.
        matched_by_repo = bool(repo and repo.lower() in by_repo)
        slug = by_repo.get(repo.lower()) if repo else None
        if not slug:
            host = normalize_host(pick_fqdn(c.get("fqdn")))
            slug = by_host.get(host) if host else None
        if not slug:
            unmapped.append(
                {
                    "uuid": c.get("uuid"),
                    "name": c.get("name"),
                    "git_repository": c.get("git_repository"),
                    "fqdn": c.get("fqdn"),
                    "instance": c.get("instance"),
                }
            )
            continue
        entry = computed.setdefault(slug, {"github_repo": None, "environments": []})
        if matched_by_repo and not entry["github_repo"]:
            entry["github_repo"] = repo
        entry["environments"].append(build_environment(c))

    for entry in computed.values():
        entry["environments"].sort(
            key=lambda e: (
                _ENV_ORDER.index(e["name"]) if e["name"] in _ENV_ORDER else len(_ENV_ORDER),
                e["name"],
            )
        )
    return computed, unmapped


