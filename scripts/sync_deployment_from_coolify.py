"""
Re-runnable, idempotent sync: populate app-brain's `github_repo` + `environments`
({name, branch, url, coolify_app_uuid}) from LIVE Coolify (the authoritative source
for uuid / branch / fqdn), extending coverage beyond the hand-set booking record.

Coolify is read-only here; app-brain is the write target. Values come straight from
Coolify — never inferred. A value Coolify doesn't provide is left null (the consumer
fails safe on a null branch).

Usage
-----
  # Coolify creds + app-brain DB are resolved at runtime; nothing secret is tracked.
  export BWS_ACCESS_TOKEN=...                       # to fetch Coolify API tokens from BWS
  export DATABASE_URL=postgresql+asyncpg://...      # the PROD app-brain DB (write target)

  python scripts/sync_deployment_from_coolify.py              # DRY RUN (default) — prints diffs
  python scripts/sync_deployment_from_coolify.py --apply      # actually write to app-brain
  python scripts/sync_deployment_from_coolify.py --apps booking-assistant

Mapping: a Coolify application -> an app-brain app by `git_repository` (case-folded
owner/repo) first, FQDN-host fallback second. One app-brain app may map to several
Coolify apps (prod + preview) -> several environment records. Coolify apps that map to
nothing are logged, never invented. Compose/Flavor-C apps are Coolify *services*, not
applications, so they never appear here — reported as "not covered (service)" upstream.
"""

