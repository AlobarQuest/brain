def _bws_get(uuid: str) -> str:
    # `--color no` is REQUIRED, not cosmetic. bws 2.0.0 emits ANSI escapes into
    # stdout even when stdout is not a TTY, so json.loads() fails on byte 0 with
    # "Expecting value" and the run dies before it reaches Coolify at all. It
    # honours neither NO_COLOR nor the absence of a terminal; only this flag, and
    # only before the subcommand. Symptom is a JSONDecodeError with no mention of
    # colour anywhere in it.
    out = subprocess.run(
        ["bws", "--color", "no", "secret", "get", uuid],
        capture_output=True,
        text=True,
        timeout=30,
    )
    if out.returncode != 0:
        raise SystemExit(f"bws secret get {uuid} failed: {out.stderr.strip()}")
    return json.loads(out.stdout)["value"]


def fetch_coolify_apps() -> list[dict]:
    """List applications across both Coolify instances. Read-only."""
    import httpx

    apps: list[dict] = []
    for instance, cfg in COOLIFY_INSTANCES.items():
        token = _bws_get(cfg["bws_uuid"])
        try:
            resp = httpx.get(
                f"{cfg['base']}/api/v1/applications",
                headers={"Authorization": f"Bearer {token}"},
                timeout=30,
            )
            resp.raise_for_status()
        except Exception as exc:  # noqa: BLE001
            print(f"  [warn] {instance} Coolify unreachable, skipping: {exc}")
            continue
        for a in resp.json():
            apps.append(
                {
                    "uuid": a.get("uuid"),
                    "name": a.get("name"),
                    "git_repository": a.get("git_repository"),
                    "git_branch": a.get("git_branch"),
                    "fqdn": a.get("fqdn"),
                    "instance": instance,
                }
            )
    return apps


async def _load_appbrain(conn) -> list[dict]:
    from sqlalchemy import text

    rows = (
        await conn.execute(
            text("SELECT slug, github_repo, deployment_url, environments FROM apps ORDER BY slug")
        )
    ).all()
    return [
        {
            "slug": r.slug,
            "github_repo": r.github_repo,
            "deployment_url": r.deployment_url,
            "environments": r.environments,
        }
        for r in rows
    ]


async def _run(apply: bool, only: set[str] | None) -> None:
    from sqlalchemy import text
    from sqlalchemy.ext.asyncio import create_async_engine

    database_url = os.environ.get("DATABASE_URL")
    if not database_url:
        raise SystemExit("DATABASE_URL env var is required")

    print("Fetching Coolify applications (read-only)…")
    coolify_apps = fetch_coolify_apps()
    print(f"  {len(coolify_apps)} Coolify applications across instances")

    engine = create_async_engine(database_url)
    changed = 0
    async with engine.connect() as conn:
        appbrain = await _load_appbrain(conn)
        current = {a["slug"]: a for a in appbrain}
        computed, unmapped = map_coolify_to_app(coolify_apps, appbrain)

        print(f"\n{'APPLY' if apply else 'DRY RUN'} — per-app diff:")
        for slug in sorted(computed):
            if only and slug not in only:
                continue
            new = computed[slug]
            cur = current.get(slug, {})
            cur_repo, cur_envs = cur.get("github_repo"), cur.get("environments") or []
            # github_repo is gap-fill only: write it solely when currently null (never
            # overwrite/case-churn an existing value). environments is Coolify-authoritative.
            repo_fill = bool(new["github_repo"]) and not cur_repo
            envs_changed = new["environments"] != cur_envs
            mark = "~" if (repo_fill or envs_changed) else "="
            print(f"  [{mark}] {slug}")
            if repo_fill:
                print(f"        github_repo: {cur_repo!r} -> {new['github_repo']!r}  (fill)")
            print(
                f"        environments: {len(cur_envs)} -> {len(new['environments'])} "
                f"{[(e['name'], e['branch'], e['coolify_app_uuid']) for e in new['environments']]}"
            )
            if apply and (repo_fill or envs_changed):
                sets = ["environments = CAST(:envs AS jsonb)"]
                params = {"slug": slug, "envs": json.dumps(new["environments"])}
                if repo_fill:
                    sets.append("github_repo = :gh")
                    params["gh"] = new["github_repo"]
                await conn.execute(
                    text(f"UPDATE apps SET {', '.join(sets)} WHERE slug = :slug"), params
                )
                changed += 1

        if apply:
            await conn.commit()

        print(f"\nUnmapped Coolify apps (no app-brain record — NOT invented): {len(unmapped)}")
        for u in unmapped:
            print(f"  - {u['instance']}:{u['name']} repo={u['git_repository']} fqdn={u['fqdn']}")
        empty = [a["slug"] for a in appbrain if a["slug"] not in computed]
        print(f"\napp-brain apps with no Coolify mapping (left unchanged): {len(empty)}")
        print(f"  {', '.join(empty)}")

    await engine.dispose()
    print(
        f"\n{'Wrote ' + str(changed) + ' app(s).' if apply else 'Dry run — no writes. Re-run with --apply to write.'}"
    )


def main() -> None:
    p = argparse.ArgumentParser(description="Sync app-brain deployment fields from live Coolify")
    p.add_argument("--apply", action="store_true", help="write to app-brain (default is dry-run)")
    p.add_argument("--apps", help="comma-separated slugs to restrict to")
    args = p.parse_args()
    only = {s.strip() for s in args.apps.split(",")} if args.apps else None
    asyncio.run(_run(apply=args.apply, only=only))


if __name__ == "__main__":
    main()
